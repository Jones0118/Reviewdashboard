// Generates src/assets/kpi-sample.json — synthetic sample data (option "b")
// for the KPI catalog entries that have no backing source field, so those KPIs
// light up in the dashboard instead of rendering "–".
//
// Values are deterministic (seeded per district) so builds are reproducible.
// All figures are per DISTRICT; the ReviewService apportions them to blocks and
// schools by each unit's share of district enrolment (same model as the other
// initiative modules).
//
// Run from the project root:  node scripts/gen-kpi-sample.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const SRC_SCHEMES = join(ROOT, 'src', 'assets', 'schemes.json');
const OUT = join(ROOT, 'src', 'assets', 'kpi-sample.json');

const schemes = JSON.parse(readFileSync(SRC_SCHEMES, 'utf8'));

// Small deterministic PRNG (mulberry32) seeded from the district name so the
// same district always produces the same sample numbers.
function seedFromString(s) {
  let h = 1779033703 ^ s.length;
  for (let i = 0; i < s.length; i++) {
    h = Math.imul(h ^ s.charCodeAt(i), 3432918353);
    h = (h << 13) | (h >>> 19);
  }
  return h >>> 0;
}
function mulberry32(a) {
  return function () {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const districts = schemes.districts.map((d) => {
  const rnd = mulberry32(seedFromString(d.name));
  const between = (lo, hi) => lo + rnd() * (hi - lo);
  const pctOf = (base, lo, hi) => Math.round(base * between(lo, hi));
  const rate1 = (lo, hi) => Math.round(between(lo, hi) * 10) / 10;

  const students = d.students ?? 100000;
  const schools = d.schools ?? 800;

  // --- Enrollment ---
  const cwsnPct = rate1(1.0, 3.8);                       // CWSN enrollment %
  const declSchools = pctOf(schools, 0.05, 0.18);        // schools with declined enrollment

  // --- Attendance ---
  const attPending = pctOf(schools, 0.02, 0.12);         // schools pending attendance marking

  // --- Infrastructure gaps (schools failing each check) ---
  const infNoToilet = pctOf(schools, 0.01, 0.06);
  const infNoWater = pctOf(schools, 0.01, 0.05);
  const infNoCwsnToilet = pctOf(schools, 0.08, 0.22);
  const infNoEb = pctOf(schools, 0.005, 0.03);
  const infNoKitchen = pctOf(schools, 0.03, 0.11);
  const infDemolish = pctOf(schools, 0.004, 0.02);
  const infRepair = pctOf(schools, 0.1, 0.3);

  // --- Digital infrastructure ---
  const ictSchools = pctOf(schools, 0.45, 0.8);
  const ictInternet = Math.round(ictSchools * between(0.65, 0.92));
  const ictNoInternet = Math.max(0, ictSchools - ictInternet);
  const ictNoTeacher = pctOf(ictSchools, 0.1, 0.35);

  // --- Academic ---
  const slasPct = rate1(42, 74);                         // SLAS score %
  const acaUp = pctOf(schools, 0.35, 0.62);              // schools improved
  const acaDown = pctOf(schools, 0.12, 0.3);             // schools declined

  // --- Schemes / grievance ---
  const breakfastExcept = pctOf(schools, 0.01, 0.07);    // breakfast exception schools
  const cmCritical = Math.round(between(2, 40));         // CM Cell critical petitions

  // --- THIRAN+ (boys/girls split of identified students) ---
  const thiranTotal = pctOf(students, 0.015, 0.05);
  const thiranBoys = Math.round(thiranTotal * between(0.48, 0.55));
  const thiranGirls = Math.max(0, thiranTotal - thiranBoys);

  // --- Scholarship ---
  const scholarPaySuccessPct = rate1(76, 98);
  const scholarPayFailed = pctOf(students, 0.002, 0.012);
  const scholarNpciInactive = pctOf(students, 0.004, 0.02);

  // --- SMC ---
  const smcEmergency = Math.round(between(1, 25));

  // --- Palli Parvai ---
  const palliZeroVisits = Math.round(between(0, 12));

  return {
    name: d.name,
    cwsnPct, declSchools,
    attPending,
    infNoToilet, infNoWater, infNoCwsnToilet, infNoEb, infNoKitchen, infDemolish, infRepair,
    ictSchools, ictInternet, ictNoInternet, ictNoTeacher,
    slasPct, acaUp, acaDown,
    breakfastExcept, cmCritical,
    thiranBoys, thiranGirls,
    scholarPaySuccessPct, scholarPayFailed, scholarNpciInactive,
    smcEmergency,
    palliZeroVisits,
  };
});

const out = {
  note: 'Synthetic sample data for KPIs without a backing source field. Generated by scripts/gen-kpi-sample.mjs; not official statistics.',
  generatedAt: new Date().toISOString(),
  districts,
};

writeFileSync(OUT, JSON.stringify(out, null, 2));
console.log(`Wrote ${districts.length} district sample records -> ${OUT}`);
